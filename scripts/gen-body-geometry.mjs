#!/usr/bin/env node
// Converts the MIT-licensed MuscleMap Swift path files into bodyGeometry.gen.ts.
// Source: https://github.com/melihcolpan/MuscleMap (MIT) — the safe upstream named in the
// openGym audit handoff; openGym's own converted paths are AGPL and must never be copied.
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'frontend/src/features/train/logic/bodyGeometry.gen.ts';
const FRONT = 'scripts/vendor/musclemap/MaleFrontPaths.swift';
const BACK = 'scripts/vendor/musclemap/MaleBackPaths.swift';

function parse(swift) {
  const shapes = {};
  for (const block of swift.split('BodyPartPathData(').slice(1)) {
    const slug = block.match(/slug:\s*\.([A-Za-z]+)/)?.[1];
    if (!slug) continue;
    const kebab = slug.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
    const paths = [...block.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(m => m[1]).filter(p => /^[Mm]/.test(p));
    if (paths.length) shapes[kebab] = (shapes[kebab] ?? []).concat(paths);
  }
  return shapes;
}

function bbox(shapes) {
  // Walk each subpath's cursor through BOTH absolute and relative commands. Many MuscleMap
  // shapes (e.g. tibialis, hip-flexors) open with a single absolute M and draw the whole rest
  // of the outline with lowercase relative curves — tracking only uppercase anchors (as the
  // prototype generator did) collapses those to a zero-size point. Endpoints + control points
  // are recorded (not true bezier extrema), which is a safe over-approximation for a bbox.
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  const mark = (x, y) => { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); };
  for (const paths of Object.values(shapes)) for (const path of paths) {
    let cx = 0, cy = 0, sx = 0, sy = 0;
    for (const seg of path.matchAll(/([A-Za-z])([^A-Za-z]*)/g)) {
      const cmd = seg[1];
      const upper = cmd.toUpperCase();
      const rel = cmd !== upper;
      // Adjacent decimals are often written without a separating space (e.g. "37.02.75" means
      // 37.02 then .75) — a plain [\d.]+ run would swallow both dots into one bad token.
      const nums = (seg[2].match(/-?\d*\.\d+(?:[eE][-+]?\d+)?|-?\d+(?:[eE][-+]?\d+)?/g) ?? []).map(Number);
      let i = 0;
      if (upper === 'Z') { cx = sx; cy = sy; continue; }
      if (upper === 'H') { while (i < nums.length) { cx = rel ? cx + nums[i++] : nums[i++]; mark(cx, cy); } continue; }
      if (upper === 'V') { while (i < nums.length) { cy = rel ? cy + nums[i++] : nums[i++]; mark(cx, cy); } continue; }
      const arity = { M: 2, L: 2, C: 6, S: 4, Q: 4, T: 2, A: 7 }[upper] ?? 2;
      while (i + arity <= nums.length) {
        const group = nums.slice(i, i + arity);
        i += arity;
        if (upper === 'A') {
          const x = rel ? cx + group[5] : group[5], y = rel ? cy + group[6] : group[6];
          mark(x, y); cx = x; cy = y;
          continue;
        }
        for (let j = 0; j + 1 < group.length; j += 2) {
          const x = rel ? cx + group[j] : group[j], y = rel ? cy + group[j + 1] : group[j + 1];
          mark(x, y);
        }
        const x = rel ? cx + group[group.length - 2] : group[group.length - 2];
        const y = rel ? cy + group[group.length - 1] : group[group.length - 1];
        cx = x; cy = y;
        if (upper === 'M') { sx = cx; sy = cy; }
      }
    }
  }
  const padX = (maxX - minX) * 0.02, padY = (maxY - minY) * 0.02;
  return [minX - padX, minY - padY, maxX - minX + 2 * padX, maxY - minY + 2 * padY].map(v => Math.round(v));
}

const front = parse(readFileSync(FRONT, 'utf8'));
const back = parse(readFileSync(BACK, 'utf8'));
const boxes = shapes => Object.fromEntries(Object.entries(shapes).map(([slug, paths]) => [slug, bbox({ one: paths })]));
const out = `// Generated by scripts/gen-body-geometry.mjs — do not hand-edit.
// Body geometry from MuscleMap (https://github.com/melihcolpan/MuscleMap), MIT License,
// Copyright (c) Melih Colpan. See NOTICE.md at the repository root.
export type BodyView = 'front' | 'back';
export const BODY: Record<BodyView, { vb: string; p: Record<string, string[]>; b: Record<string, [number, number, number, number]> }> = {
  front: { vb: '${bbox(front).join(' ')}', p: ${JSON.stringify(front)}, b: ${JSON.stringify(boxes(front))} },
  back: { vb: '${bbox(back).join(' ')}', p: ${JSON.stringify(back)}, b: ${JSON.stringify(boxes(back))} },
};
`;
if (process.argv.includes('--check')) {
  process.exit(readFileSync(OUT, 'utf8') === out ? 0 : 1);
}
writeFileSync(OUT, out);
console.log('front:', Object.keys(front).length, 'shapes · back:', Object.keys(back).length, 'shapes');
