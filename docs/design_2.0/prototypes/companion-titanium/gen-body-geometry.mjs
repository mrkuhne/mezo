#!/usr/bin/env node
// Converts the MIT-licensed MuscleMap Swift path files into body-geometry.js.
// Source: https://github.com/melihcolpan/MuscleMap (MIT) — the safe upstream named in the
// openGym audit handoff; openGym's own converted paths are AGPL and must never be copied.
// Usage: node gen-body-geometry.mjs <MaleFrontPaths.swift> <MaleBackPaths.swift>
import { readFileSync, writeFileSync } from 'node:fs';

const [frontFile, backFile] = process.argv.slice(2);
if (!frontFile || !backFile) { console.error('usage: gen-body-geometry.mjs <front.swift> <back.swift>'); process.exit(1); }

function parse(swift) {
  const shapes = {};
  const blocks = swift.split('BodyPartPathData(').slice(1);
  for (const block of blocks) {
    const slug = block.match(/slug:\s*\.([A-Za-z]+)/)?.[1];
    if (!slug) continue;
    const kebab = slug.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
    const paths = [...block.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(m => m[1]).filter(p => /^[Mm]/.test(p));
    if (paths.length) shapes[kebab] = (shapes[kebab] ?? []).concat(paths);
  }
  return shapes;
}

function bbox(shapes) {
  // Absolute anchors are plenty for a viewBox: every subpath opens with an absolute M and the
  // large shapes pin the extremes. A 2% margin absorbs whatever the relative curves add.
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const paths of Object.values(shapes)) for (const path of paths) {
    for (const seg of path.matchAll(/([A-Z])([^A-Za-z]*)/g)) {
      const nums = (seg[2].match(/-?[\d.]+/g) ?? []).map(Number);
      if (seg[1] === 'H') { for (const n of nums) { minX = Math.min(minX, n); maxX = Math.max(maxX, n); } continue; }
      if (seg[1] === 'V') { for (const n of nums) { minY = Math.min(minY, n); maxY = Math.max(maxY, n); } continue; }
      for (let i = 0; i + 1 < nums.length; i += 2) {
        minX = Math.min(minX, nums[i]); maxX = Math.max(maxX, nums[i]);
        minY = Math.min(minY, nums[i + 1]); maxY = Math.max(maxY, nums[i + 1]);
      }
    }
  }
  const padX = (maxX - minX) * 0.02, padY = (maxY - minY) * 0.02;
  return [minX - padX, minY - padY, maxX - minX + 2 * padX, maxY - minY + 2 * padY].map(v => Math.round(v));
}

const front = parse(readFileSync(frontFile, 'utf8'));
const back = parse(readFileSync(backFile, 'utf8'));
const boxes = shapes => Object.fromEntries(Object.entries(shapes).map(([slug, paths]) => [slug, bbox({ one: paths })]));
const out = `// Generated by gen-body-geometry.mjs — do not hand-edit.
// Body geometry from MuscleMap (https://github.com/melihcolpan/MuscleMap), MIT License,
// Copyright (c) Melih Colpan. See NOTICE.md beside this file for the full license text.
export const BODY = {
  front: { vb: '${bbox(front).join(' ')}', p: ${JSON.stringify(front)}, b: ${JSON.stringify(boxes(front))} },
  back: { vb: '${bbox(back).join(' ')}', p: ${JSON.stringify(back)}, b: ${JSON.stringify(boxes(back))} },
};
`;
writeFileSync('body-geometry.js', out);
console.log('front:', Object.keys(front).length, 'shapes · back:', Object.keys(back).length, 'shapes');
console.log('front slugs:', Object.keys(front).join(', '));
console.log('back slugs:', Object.keys(back).join(', '));
